let uiLang = "zh";
try {
  const saved = localStorage.getItem(I18N_KEY);
  if (saved === "en" || saved === "zh") uiLang = saved;
} catch (err) {
  /* ignore */
}

function t(key, vars) {
  const pack = STRINGS[uiLang] || STRINGS.zh;
  let s = pack[key] || STRINGS.zh[key] || key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ""));
  }
  return s;
}

function applyI18n() {
  try {
    document.documentElement.lang = uiLang === "en" ? "en" : "zh-Hant";
    document.documentElement.setAttribute("data-lang", uiLang);
    document.title = t("docTitle");
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (key) el.setAttribute("aria-label", t(key));
    });
    const zhBtn = document.getElementById("lang-zh");
    const enBtn = document.getElementById("lang-en");
    if (zhBtn) zhBtn.classList.toggle("is-on", uiLang === "zh");
    if (enBtn) enBtn.classList.toggle("is-on", uiLang === "en");
    if (typeof window.onLangChange === "function") window.onLangChange();
  } catch (err) {
    console.error(err);
  }
}

function setLang(lang) {
  if (lang !== "zh" && lang !== "en") return;
  uiLang = lang;
  try {
    localStorage.setItem(I18N_KEY, lang);
  } catch (err) {
    /* ignore */
  }
  applyI18n();
}

document.addEventListener("click", (ev) => {
  const btn = ev.target && ev.target.closest && ev.target.closest("button[data-lang]");
  if (!btn) return;
  setLang(btn.getAttribute("data-lang"));
});

applyI18n();
