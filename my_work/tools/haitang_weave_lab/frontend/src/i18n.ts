const zhHans: Record<string, string> = Object.fromEntries(Object.entries(zh).map(([key, value]) => [key, toHans(value)]));

export const copy: Record<Lang, Record<string, string>> = { "zh-Hans": zhHans, "zh-Hant": zh, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let text = copy[lang][key] ?? copy["zh-Hant"][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(`{${name}}`, String(value));
    }
  }
  return text;
}

export function presetLabel(lang: Lang, id: string, fallback: string): string {
  return copy[lang][`preset.${id}`] ?? fallback;
}
